const escapeHtml = (value: string): string =>
  value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");

/**
 * Fills `{{name}}` placeholders. Values are escaped (the template is HTML);
 * a placeholder without a value, or an unknown one, becomes a dash.
 */
export const renderLegalTemplate = (
  template: string,
  values: Record<string, string | null | undefined>,
): string =>
  template.replace(/\{\{(\w+)\}\}/g, (_, key: string) => {
    const value = values[key]?.trim();
    return value ? escapeHtml(value) : "—";
  });

/** The four documents, filled from the owner's values. */
export const renderLegalDocument = (
  kind: LegalDocumentKind,
  values: Record<string, string | null | undefined>,
): string => renderLegalTemplate(LEGAL_TEMPLATES[kind], values);

/** Current date in Russian format, for "дата редакции". */
export const formatRussianDate = (date: Date): string =>
  date.toLocaleDateString("ru-RU", { day: "2-digit", month: "2-digit", year: "numeric" });
